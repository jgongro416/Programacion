def main():
    num1=float(input("Dime el primer numero: "))
    num2=float(input("Dime el segundo numero: "))
    num3=float(input("Dime el tercer numero: "))
    suma= num1+num2+num3
    print(f"La suma de los numeros {num1}, {num2} y {num3} da un total de {suma}")
if __name__=="__main__":
    main()